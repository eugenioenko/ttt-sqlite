#!/usr/bin/env python3
"""Bundle src/**/*.lua into init.lua, the single file ttt loads.

Each source file becomes a module named after its path: src/features/table/data.lua
is require("features.table.data"), and src/components/init.lua is
require("components"). The bundle defines a local require that serves these
modules and falls back to ttt's own require for ttt.* modules.

    scripts/build.py           write init.lua
    scripts/build.py --check   fail if init.lua is out of date
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "init.lua"
ENTRY = "main"

PRELUDE = """\
-- Generated by scripts/build.py from src/. Edit the files in src/ instead.
local __modules, __loaded, __loading = {}, {}, {}
local __require = require
local function require(name)
  local cached = __loaded[name]
  if cached ~= nil then
    return cached
  end
  local load = __modules[name]
  if not load then
    return __require(name)
  end
  if __loading[name] then
    error("circular require of module " .. name .. " at load time; require it inside a function instead", 2)
  end
  __loading[name] = true
  local value = load()
  __loading[name] = nil
  if value == nil then
    value = true
  end
  __loaded[name] = value
  return value
end
"""


def module_name(path: pathlib.Path) -> str:
    parts = list(path.relative_to(SRC).with_suffix("").parts)
    if parts[-1] == "init" and len(parts) > 1:
        parts.pop()
    return ".".join(parts)


def bundle() -> str:
    files = sorted(SRC.rglob("*.lua"))
    names = {}
    for path in files:
        name = module_name(path)
        if name in names:
            sys.exit(f"build: {path} and {names[name]} both define module {name}")
        names[name] = path
    if ENTRY not in names:
        sys.exit(f"build: missing entry module src/{ENTRY}.lua")

    out = [PRELUDE]
    for name, path in names.items():
        source = path.read_text(encoding="utf-8").rstrip("\n")
        rel = path.relative_to(ROOT)
        out.append(f'\n-- {rel} {"-" * max(3, 74 - len(str(rel)))}\n')
        out.append(f'__modules["{name}"] = function()\n{source}\nend\n')
    out.append(f'\nrequire("{ENTRY}")\n')
    return "".join(out)


def main() -> None:
    text = bundle()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit("build: init.lua is out of date, run scripts/build.py")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"build: wrote {OUT.relative_to(ROOT)} from {len(list(SRC.rglob('*.lua')))} modules")


if __name__ == "__main__":
    main()
